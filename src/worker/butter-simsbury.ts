/**
 * The Simsbury pack.
 *
 * Butter's home town, written down: the streets, the high school's staff and
 * teams, the town's own history, the shops, the landmarks and the people. Two
 * of these cards turn up in every Daily Dive (the dive overlays them on
 * whichever deck it dealt, live or local) and two or three in every Butter
 * Party game, spaced so a short game still reads as a normal table.
 *
 * Every answer here is a real thing in or about Simsbury, taken from the town's
 * own street index, the school's staff and club pages, the historical society
 * and the local press. The shipped cards cap out at about 1,200 answers (that is
 * the ceiling in the generated bank too), so these are capped the same way. The
 * order of every list matters: the obvious answers come first and the tiers are
 * read off that order, so "Hopmeadow Street" is Margarine and "Quorn Hut Road"
 * is a One in a Butter Churn.
 */

import type { BankCard } from './butter-cards'

/** The tier of an answer at a position, read the same way `answerTier` reads a
 *  card that arrived without tiers. */
function tierAt(index: number, total: number): string {
  const ratio = total > 1 ? index / (total - 1) : 1
  if (ratio <= 0.08) return 'plankton'
  if (ratio <= 0.18) return 'tooclever'
  if (ratio <= 0.36) return 'schooler'
  if (ratio <= 0.6) return 'rare'
  if (ratio <= 0.82) return 'deepcut'
  return 'krillion'
}

/** Flattened, so a card never carries the same answer twice. */
function key(value: string): string {
  return value
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, ' ')
    .trim()
}

/** At most the shipped card's own ceiling, in the order the list was written. */
const CAP = 1_203

function build(prompt: string, answers: string[]): BankCard {
  const seen = new Set<string>()
  const out: string[] = []
  for (const answer of answers) {
    const flat = key(answer)
    if (!flat || seen.has(flat)) continue
    seen.add(flat)
    out.push(answer)
    if (out.length >= CAP) break
  }
  return { prompt, answers: out, tiers: out.map((_, index) => tierAt(index, out.length)) }
}

