/** Road, Rd, Street, St …: people type the suffix whichever way they like. */
function streetForms(name: string): string[] {
  const forms = [name]
  const trimmed = name.replace(/\s+(Street|Road|Lane|Drive|Court|Way|Place|Boulevard|Turn|Crossing|Path|Terrace|Circle|Ridge|Run)$/i, '')
  if (trimmed !== name) forms.push(trimmed)
  if (/ Street$/i.test(name)) forms.push(name.replace(/ Street$/i, ' St'))
  if (/ Road$/i.test(name)) forms.push(name.replace(/ Road$/i, ' Rd'))
  if (/ Lane$/i.test(name)) forms.push(name.replace(/ Lane$/i, ' Ln'))
  if (/ Drive$/i.test(name)) forms.push(name.replace(/ Drive$/i, ' Dr'))
  return forms
}

