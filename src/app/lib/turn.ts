// The reply currently being generated, held outside React so it survives the
// move from "/" to "/c/:id" when a first message creates its conversation.
// There is at most one turn at a time; the page for its conversation renders
// it under the saved messages and folds it into the query cache when done.

import { useSyncExternalStore } from 'react'
import type { QueryClient } from '@tanstack/react-query'

import type { AnalysisInfo, AnalysisJob, BuildInfo, CanvasInfo, ChatEvent, Conversation, Me, Message, ProofInfo, ProofJob, ResearchInfo, Source, TeamInfo } from '../../shared/types'
import { ApiError, type ConversationPage } from './api'
import { runAnalysisJob } from './analysis-runner'
import { getDataset } from './dataset-store'
import { runProofJob } from './proof-runner'
import { streamChat, type ChatRequest } from './stream'

export type Turn = {
  /** Set once the server has told us which conversation this is. */
  conversationId: string | null
  /** The user message being answered (optimistic until `start` arrives). */
  userMessage: Message | null
  assistantMessageId: string | null
  text: string
  /** Reasoning streamed before the answer, when the model exposed it. */
  reasoning: string
  /** What the deep pass is doing while there is no text yet. */
  statusText: string
  /** Completed progress messages, in order. */
  statusLog: string[]
  /** A non-fatal problem shown while the turn runs (e.g. search is down). */
  notice: string
  /** Web results retrieved before the answer. */
  sources: Source[]
  /** The free team's check, when a legacy Team reply is replayed. */
  team?: TeamInfo
  /** What Proof is checking, once the server has decided. */
  proof?: ProofInfo
  /** The citations and checks attached to a Research report. */
  research?: ResearchInfo
  /** What the browser ran for an Analyze reply. */
  analysis?: AnalysisInfo
  /** A page generated by Build mode. */
  build?: BuildInfo
  /** A study set generated by Canvas mode. */
  canvas?: CanvasInfo
  /** The browser run the server is waiting for. */
  analysisJob?: AnalysisJob
  /** The browser run the server is waiting for, when code is checking. */
  proofJob?: ProofJob
  status: 'waiting' | 'streaming' | 'error'
  error: string | null
  model: string
  stop(): void
}

let turn: Turn | null = null
const listeners = new Set<() => void>()
const emit = () => listeners.forEach((listener) => listener())
const set = (next: Turn | null) => {
  turn = next
  emit()
}
const update = (patch: Partial<Turn>) => turn && set({ ...turn, ...patch })

export function useTurn(): Turn | null {
  return useSyncExternalStore(
    (listener) => {
      listeners.add(listener)
      return () => listeners.delete(listener)
    },
    () => turn,
    () => turn,
  )
}

const localId = () => `local-${Math.random().toString(36).slice(2)}`

/**
 * Starts a turn. `onConversation` fires once when a new conversation's id is
 * known (so the page can navigate to it). Rejects only when the request was
 * refused before any reply began; stream errors end up on the turn itself.
 */
export async function startTurn(
  client: QueryClient,
  request: ChatRequest,
  options: { onConversation?: (conversation: Conversation) => void; onStarted?: (message: Message) => void } = {},
): Promise<void> {
  if (turn) turn.stop()
  const controller = new AbortController()
  const optimisticUser: Message | null = request.regenerate
    ? null
    : {
        id: localId(),
        conversationId: request.conversationId ?? '',
        role: 'user',
        content: request.content ?? '',
        model: null,
        interrupted: false,
        createdAt: Date.now(),
        ...(request.attachments?.length
          ? {
              attachments: request.attachments.map((attachment) => ({
                id: localId(),
                name: attachment.name,
                mime: attachment.mime,
                size: attachment.size,
                kind: attachment.kind,
                ...(attachment.kind === 'image' ? { url: attachment.data } : {}),
              })),
            }
          : {}),
      }
  set({
    conversationId: request.conversationId ?? null,
    userMessage: optimisticUser,
    assistantMessageId: null,
    text: '',
    reasoning: '',
    statusText: '',
    statusLog: [],
    notice: '',
    sources: [],
    team: undefined,
    proof: undefined,
    research: undefined,
    analysis: undefined,
    build: undefined,
    canvas: undefined,
    analysisJob: undefined,
    proofJob: undefined,
    status: 'waiting',
    error: null,
    model: request.model ?? '',
    stop: () => controller.abort(),
  })

  const finish = (message: Message | null, usage?: Me['usage']) => {
    const current = turn
    if (!current?.conversationId) return set(null)
    const id = current.conversationId
    client.setQueryData<ConversationPage>(['conversation', id], (old) => {
      if (!old) return old
      let messages = old.messages
      if (request.regenerate) {
        const lastUser = [...messages].reverse().find((m) => m.role === 'user')
        if (lastUser) messages = messages.filter((m) => m.createdAt <= lastUser.createdAt)
      } else if (current.userMessage && !messages.some((m) => m.id === current.userMessage!.id)) {
        messages = [...messages, current.userMessage]
      }
      if (message) messages = [...messages, message]
      return { ...old, messages, conversation: { ...old.conversation, model: current.model || old.conversation.model, updatedAt: Date.now() } }
    })
    if (usage) client.setQueryData<Me>(['me'], (old) => old && { ...old, usage: { ...old.usage, ...usage } })
    void client.invalidateQueries({ queryKey: ['conversations'] })
    set(null)
  }

  const onEvent = (event: ChatEvent) => {
    if (!turn) return
    switch (event.type) {
      case 'start': {
        const isNew = !request.conversationId
        update({ conversationId: event.conversation.id, userMessage: event.userMessage, assistantMessageId: event.assistantMessageId, model: event.conversation.model })
        if (isNew) {
          client.setQueryData<ConversationPage>(['conversation', event.conversation.id], { conversation: event.conversation, messages: [event.userMessage] })
          client.setQueryData<{ items: Conversation[] }>(['conversations'], (old) => ({ items: [event.conversation, ...(old?.items ?? [])] }))
          options.onConversation?.(event.conversation)
        } else if (!request.regenerate) {
          client.setQueryData<ConversationPage>(['conversation', event.conversation.id], (old) => old && { ...old, messages: [...old.messages, event.userMessage] })
          update({ userMessage: null })
        }
        options.onStarted?.(event.userMessage)
        break
      }
      case 'status': {
        const statusLog = turn.statusLog[turn.statusLog.length - 1] === event.text ? turn.statusLog : [...turn.statusLog, event.text].slice(-8)
        update({ statusText: event.text, statusLog })
        break
      }
      case 'notice':
        update({ notice: event.text })
        break
      case 'sources':
        update({ sources: event.sources })
        break
      case 'team':
        update({ team: event.team })
        break
      case 'proof':
        update({ proof: event.proof, proofJob: event.job })
        break
      case 'research':
        update({ research: event.research })
        break
      case 'analysis':
        update({ analysis: event.analysis, analysisJob: event.job })
        break
      case 'build':
        update({ build: event.build })
        break
      case 'canvas':
        update({ canvas: event.canvas })
        break
      case 'reasoning':
        update({ reasoning: turn.reasoning + event.text, status: 'streaming', statusText: '' })
        break
      case 'delta':
        update({ text: turn.text + event.text, status: 'streaming', statusText: '' })
        break
      case 'done': {
        const job = turn.proofJob
        const analysisJob = turn.analysisJob
        const conversationId = turn.conversationId
        finish(event.message, event.usage)
        // Code proof is settled after the reply is saved: the browser runs the
        // tests and posts the report, and the endpoint may ask for one repair.
        if (job && conversationId) void settleProof(client, conversationId, job)
        // Analyze follows the same pattern; its dataset is read from IndexedDB.
        if (analysisJob && conversationId) void settleAnalysis(client, conversationId, analysisJob)
        // The send recorded provider health; let the picker show it.
        void client.invalidateQueries({ queryKey: ['providers'] })
        break
      }
      case 'error':
        update({ status: 'error', error: event.message })
        void client.invalidateQueries({ queryKey: ['providers'] })
        break
    }
  }

  try {
    await streamChat(request, { signal: controller.signal, onEvent })
    // The stream closed without `done` or `error`: treat whatever arrived as the reply.
    if (turn && turn.status !== 'error') {
      const current = turn
      const job = current.proofJob
      const analysisJob = current.analysisJob
      finish(
        current.text && current.assistantMessageId && current.conversationId
          ? { id: current.assistantMessageId, conversationId: current.conversationId, role: 'assistant', content: current.text, model: current.model || null, interrupted: true, createdAt: Date.now(), reasoning: current.reasoning || undefined, sources: current.sources.length ? current.sources : undefined, team: current.team, proof: current.proof, research: current.research, analysis: current.analysis, build: current.build, canvas: current.canvas }
          : null,
      )
      if (job && current.conversationId) void settleProof(client, current.conversationId, job)
      if (analysisJob && current.conversationId) void settleAnalysis(client, current.conversationId, analysisJob)
    }
  } catch (error) {
    if (controller.signal.aborted) {
      // Stopped by the user: keep the partial reply, marked as such.
      const current = turn
      const job = current?.proofJob
      const analysisJob = current?.analysisJob
      finish(
        current?.text && current.assistantMessageId && current.conversationId
          ? { id: current.assistantMessageId, conversationId: current.conversationId, role: 'assistant', content: current.text, model: current.model || null, interrupted: true, createdAt: Date.now(), reasoning: current.reasoning || undefined, sources: current.sources.length ? current.sources : undefined, team: current.team, proof: current.proof, research: current.research, analysis: current.analysis, build: current.build, canvas: current.canvas }
          : null,
      )
      if (job && current?.conversationId) void settleProof(client, current.conversationId, job)
      if (analysisJob && current?.conversationId) void settleAnalysis(client, current.conversationId, analysisJob)
      return
    }
    set(null)
    if (error instanceof ApiError) throw error
    throw new ApiError(0, 'Could not reach the server.')
  }
}

/**
 * Runs the browser proof job and posts each report. The endpoint replies with
 * either the final verdict or one repaired candidate to run, so the loop is
 * bounded by the server's two-round limit. A closed tab simply leaves the
 * record checking; it never turns into a pass.
 */
async function settleProof(client: QueryClient, conversationId: string, initial: ProofJob): Promise<void> {
  let job: ProofJob | undefined = initial
  for (let round = 0; round < 3 && job; round += 1) {
    const report = await runProofJob(job)
    try {
      const response = await fetch(`/api/proof/${job.messageId}/result`, {
        method: 'POST',
        credentials: 'same-origin',
        headers: { 'content-type': 'application/json' },
        body: JSON.stringify({ round: job.round, report }),
      })
      if (!response.ok) break
      const body = (await response.json()) as { done?: boolean; job?: ProofJob }
      job = body.done ? undefined : body.job
    } catch {
      break
    }
  }
  await client.invalidateQueries({ queryKey: ['conversation', conversationId] })
}

/** Runs the browser analysis and persists its stdout/chart on the reply. */
export async function settleAnalysis(client: QueryClient, conversationId: string, job: AnalysisJob): Promise<void> {
  const stored = await getDataset(job.datasetId)
  const result = stored
    ? await runAnalysisJob(job.code, stored.csv)
    : { ok: false, loadError: 'The dataset is not saved in this browser. Attach the file again to rerun.' }
  try {
    await fetch(`/api/analysis/${job.messageId}/result`, {
      method: 'POST',
      credentials: 'same-origin',
      headers: { 'content-type': 'application/json' },
      body: JSON.stringify({ result }),
    })
  } catch {
    // A closed tab or a lost connection leaves the record checking. The server
    // decays it to unverified rather than pretending it ran.
  }
  await client.invalidateQueries({ queryKey: ['conversation', conversationId] })
}

/** Removes the turn's error so the page is back to its saved messages. */
export function dismissTurn() {
  set(null)
}
